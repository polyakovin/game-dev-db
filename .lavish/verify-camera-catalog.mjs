import { chromium } from '/Users/polyakovin/repos/game-dev-db/node_modules/playwright/index.mjs';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = '/Users/polyakovin/repos/game-dev-db/.lavish';
const file = `file://${base}/phone-camera-mechanics.html`;
const catalog = JSON.parse(await readFile(`${base}/phone-camera-mechanics.json`, 'utf8'));
assert.equal(catalog.groups.length, 21);
assert.equal(catalog.groups.flatMap(g => g.items).length, 168);
for (const g of catalog.groups) for (const s of g.sources) assert(catalog.sources[s]);
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(file);
assert.equal(await page.locator('.family').count(),21);
assert.equal(await page.locator('tbody tr').count(),168);
assert.equal(await page.locator('tbody tr:visible').count(),168);
assert.equal(await page.locator('h1').count(),1);
await page.locator('#search').fill('бумага');
assert((await page.locator('tbody tr:visible').count())>0);
assert((await page.locator('tbody tr:visible').count())<168);
await page.locator('#reset').click();
await page.locator('#family').selectOption('hands');
assert.equal(await page.locator('tbody tr:visible').count(),8);
await page.locator('#tech').selectOption('experimental');
assert.equal(await page.locator('tbody tr:visible').count(),0);
assert(await page.locator('#empty').isVisible());
await page.locator('#reset').click();
await page.locator('#tech').selectOption('experimental');
assert.equal(await page.locator('tbody tr:visible').count(),3);
await page.locator('#reset').click();
await page.locator('#search').fill('несуществующий-запрос');
await page.locator('.toc nav a[href="#memory"]').click();
assert.equal(await page.locator('tbody tr:visible').count(),168);
await page.goto(`${file}#cam-168`);
assert(await page.locator('#cam-168').isVisible());
await page.goto(file);
const downloadPromise=page.waitForEvent('download');
await page.locator('#download').click();
const download=await downloadPromise;
assert.equal(download.suggestedFilename(),'phone-camera-mechanics.json');
await download.saveAs('/private/tmp/camera-catalog-download.json');
assert.deepEqual(JSON.parse(await readFile('/private/tmp/camera-catalog-download.json','utf8')),catalog);
for(const width of [1440,768,390]){
  await page.setViewportSize({width,height:1000});
  await page.goto(file);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  assert.equal(overflow,false,`page overflows at ${width}`);
  if(width===1440)await page.screenshot({path:`${base}/camera-catalog-desktop.png`});
  if(width===390){
    await page.locator('#framing').scrollIntoViewIfNeeded();
    await page.screenshot({path:`${base}/camera-catalog-mobile.png`});
    await page.locator('#search').fill('фото');
    assert((await page.locator('tbody tr:visible').count())>0);
  }
}
await page.setViewportSize({width:1440,height:1000});
await page.goto(file);
await page.keyboard.press('Tab');
assert.equal(await page.locator(':focus').textContent(),'Перейти к каталогу');
await page.keyboard.press('Enter');
assert.equal(new URL(page.url()).hash,'#catalog');
const noJs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
const noJsPage=await noJs.newPage();await noJsPage.goto(file);
assert.equal(await noJsPage.locator('tbody tr:visible').count(),168);
assert.equal(await noJsPage.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Verified: 168 records, 21 families; search, combined filters, empty state, reset, anchors, JSON download, keyboard entry, no-JS reading, no overflow at 1440/768/390px.');
